#!/usr/bin/env python3
"""Writes src/icons.rs from lucide's icon files, so the prototype draws the same icons as Fleet's client.

    python3 tools/gen-icons.py <path to node_modules/lucide-vue-next> message-square zap ...

Rune's icon bodies are a flat list of SVG elements, each carrying its own stroke attributes (there
is no <g> inheritance), so lucide's shared attributes are repeated on every element.
"""
import pathlib
import re
import sys

STROKE = 'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" fill="none"'


def elements(js: str):
    """Yields (tag, attrs) from a lucide icon module's node list."""
    for tag, body in re.findall(r'\[\s*"(\w+)",\s*\{(.*?)\}\s*\]', js, flags=re.S):
        attrs = dict(re.findall(r'(\w+):\s*"([^"]*)"', body))
        attrs.pop("key", None)
        yield tag, attrs


def main():
    lucide = pathlib.Path(sys.argv[1]) / "dist" / "esm" / "icons"
    names = sys.argv[2:]
    out = [
        "//! Lucide icons (ISC licence), the ones Fleet's client draws. Generated by tools/gen-icons.py;",
        "//! add a name to the list in the README's command and run it again rather than editing this file.",
        "#![allow(dead_code)]",
        "use rune::Icon;",
        "",
    ]
    for name in names:
        js = (lucide / f"{name}.js").read_text()
        body = "".join(
            "<{} {} {}/>".format(tag, " ".join(f'{k}="{v}"' for k, v in attrs.items()), STROKE)
            for tag, attrs in elements(js)
        )
        const = name.upper().replace("-", "_")
        out.append(f'pub static {const}: Icon = Icon {{ name: "lucide-{name}", view: 24.0, body: r#"{body}"# }};')
    target = pathlib.Path(__file__).resolve().parent.parent / "src" / "icons.rs"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {len(names)} icons to {target}")


if __name__ == "__main__":
    main()
